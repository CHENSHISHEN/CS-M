export const createMessages = (locale = 'zh', overrides) => {
  const base = MESSAGE_PACKS[locale] || MESSAGE_PACKS.zh;
  const pack = overrides ? { ...base, ...overrides } : base;
  return (key, params) => {
    let value = pack[key];
    if (value == null) value = MESSAGE_PACKS.zh[key] != null ? MESSAGE_PACKS.zh[key] : key;
    if (params) {
      Object.keys(params).forEach((p) => {
        value = String(value).split(`{${p}}`).join(params[p]);
      });
    }
    return value;
  };
};

export default createMessages;
